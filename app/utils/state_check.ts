export default function stateCheck(state: string, country: string) {
    const c = country.toLowerCase()
    if (c === "us" || c === "united states" || c === "united states of america") return USstate(state).split("-")[1]
    if (c === "ca" || c === "canada") return CAstate(state).split("-")[1]
    if (c === "mx" || c === "mexico") return MXState(state).split("-")[1]
    return state.toUpperCase()
}